// ——— My runs: a few weeks of practice, mostly Python, some JavaScript and Go ———

interface HistoryRun {
  id: string
  language: string
  snippet: string
  fingerprint: string
  length: Snippet['length']
  aids: TypingAids
  wpm: number
  rawWpm: number
  accuracy: number
  consistency: number | null
  seconds: number
  finishedAt: string
  submission?: { status: 'accepted'; at: string; runId: string; rank: number; best: boolean; bestForAids: boolean }
}
const history: HistoryRun[] = []
const historyLogs: { id: string; log: LogEntry[] }[] = []
const plan: [string, number, number][] = [
  // language, snippet index, how many runs
  ['python', 0, 6],
  ['python', 1, 4],
  ['python', 4, 3],
  ['javascript', 0, 4],
  ['javascript', 3, 2],
  ['go', 0, 3],
]
let n = 0
for (const [langId, index, count] of plan) {
  const l = lang(langId)
  const s = l.snippets[index]
  const print = await fingerprint(s.code)
  for (let k = 0; k < count; k++) {
    n++
    const aids = aidsOf(['110', '111', '000'][k % 3])
    // Getting a little faster with practice.
    const r = played(l, s, aids, 500 + n, 0.9 + k * 0.12)
    const id = `h-${String(n).padStart(3, '0')}`
    const finishedAt = at(20 - n * 0.6, n * 7)
    const { log, ...result } = r
    history.push({ id, language: l.id, snippet: s.name, fingerprint: print, length: s.length, aids, ...result, finishedAt })
    historyLogs.push({ id, log })
  }
}
// The test player's leaderboard run is in their history too, as sent.
const mine = history.find((r) => r.language === 'python' && r.snippet === board.name)!
mine.submission = { status: 'accepted', at: mine.finishedAt, runId: runIds[TEST_PLAYER.id], rank: 18, best: true, bestForAids: true }

mkdirSync(DIR, { recursive: true })
writeFileSync(`${DIR}/seed.sql`, lines.join('\n\n') + '\n')
writeFileSync(`${DIR}/history.json`, JSON.stringify({ format: 'syntype-history', version: 1, exportedAt: FIXED_NOW, runs: history, logs: historyLogs }) + '\n')
console.log(`seed.sql: ${players.length} players, ${bests.length} best rows, ${logs.length} kept logs; history.json: ${history.length} runs`)
