const versions: string[] = []
for (const s of python.snippets) versions.push(`  (${[await fingerprint(s.code), 'python', s.name, s.length, s.code, at(60)].map(sql).join(', ')})`)
// An older text of the main board's snippet, with a score of its own: an archived board.
