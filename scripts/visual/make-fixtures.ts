const bests: string[] = []
const logs: string[] = []
const runIds: Record<string, string> = {}
/** One player's best on a snippet: its 'any' row and its aid-combination row, plus its log when kept. */
async function best(playerId: string, s: Snippet, print: string, aids: string, seed: number, speed: number, daysAgo: number, keepLog: boolean) {
  const r = played(python, s, aidsOf(aids), seed, speed)
  const runId = `run-${playerId}-${s.name.replace(/\W/g, '')}`
  const row = (key: string) => `  (${[playerId, print, key, 'python', runId, r.wpm, r.rawWpm, r.accuracy, r.seconds, aids, at(daysAgo, seed % 50)].map(sql).join(', ')})`
  bests.push(row('any'), row(aids))
  if (keepLog) logs.push(`  (${[sql(runId), sql(playerId), sql(print), hex(await packLog(r.log)), sql(at(daysAgo))].join(', ')})`)
  return runId
}

